/**
 * Returns true when a grid description is absent or the legacy sentinel value.
 * @param {string|null|undefined} description - Raw description from the data section grid.
 * @returns {boolean} True when the description should not be shown.
 */
export function isMissingGridDescription(description) {
    const trimmed = (description || '').trim();
    return trimmed === '' || trimmed.toLowerCase() === 'unknown';
}

/**
 * Returns the user-facing label for a data section grid in the Grid Layout Editor dropdown.
 * Description is display-only; matching uses stable grid Name ids.
 * @param {object} gridOption - Grid entry from DataSectionsDefinition.Grids.
 * @param {Array<{Key: string, Value: string}>} language - Login language catalogue.
 * @returns {string} Translated description, grid Name, or 'Unknown'.
 */
export function getGridDisplayText(gridOption, language = []) {
    if (!gridOption) {
        return 'Unknown';
    }

    const rawDescription = gridOption.description || gridOption.Description;
    if (!isMissingGridDescription(rawDescription)) {
        return TranslateTag(rawDescription, language) || rawDescription;
    }

    const rawName = gridOption.name || gridOption.Name;
    if (rawName) {
        return rawName;
    }

    return 'Unknown';
}
