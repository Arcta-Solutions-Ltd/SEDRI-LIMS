namespace arc.domain.Configuration.ReportsConfig
{
    /// <summary>
    /// Represents a section source configuration for a report.
    /// </summary>
    public class SectionSource
    {
        /// <summary>
        /// Gets or sets the name of the section source.
        /// </summary>
        public string Name { get; set; }

        /// <summary>
        /// Gets or sets the source type of the section.
        /// </summary>
        public string Source { get; set; }
    }
}
